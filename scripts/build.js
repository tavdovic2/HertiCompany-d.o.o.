#!/usr/bin/env node
"use strict";
// Builds the complete static site into dist/ from src/.

const fs = require("fs");
const path = require("path");
const hc = require("../src/assets/js/templates.js");
const components = require("../src/templates/components.js");
const layout = require("../src/templates/layout.js");
const pages = require("../src/templates/pages.js");
const seoModule = require("./lib/seo.js");
const { loadData, validate } = require("./lib/data.js");
const { createSitemap } = require("./lib/sitemap.js");
const { webpSize } = require("./lib/images.js");
const { md5, readText, writeFile, copyDir } = require("./lib/files.js");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "src");
const DIST = path.join(ROOT, "dist");
const IMAGES = path.join(SRC, "assets", "images");
const STATE = path.join(__dirname, "build-state.json");
const now = new Date();

/* Data */
let data;
try {
  data = loadData(path.join(SRC, "data"));
} catch (e) {
  console.error(e.message);
  process.exit(1);
}
const { errors, warnings } = validate(data, IMAGES);
if (errors.length) {
  console.error("Build failed:\n- " + errors.join("\n- "));
  process.exit(1);
}

/* Static files and assets */
fs.rmSync(DIST, { recursive: true, force: true });
copyDir(path.join(SRC, "static"), DIST);
copyDir(path.join(SRC, "assets"), path.join(DIST, "assets"));

// Shelf images on the home page: width and height read from the files themselves
const shelfDir = path.join(IMAGES, "products", "shelf");
const shelf = Object.fromEntries(fs.readdirSync(shelfDir).filter(f => f.endsWith(".webp")).sort()
  .map(f => [path.basename(f, ".webp"), webpSize(path.join(shelfDir, f))]));

// Browser data: only the fields main.js needs (search, inquiry form, shelf)
const { company, categories, products } = data;
const catalog = {
  company: { phone: company.phone, phoneDial: company.phoneDial, email: company.email, web3formsKey: company.web3formsKey },
  categories: categories.map(({ id, name }) => ({ id, name })),
  products: products.map(({ id, name, brand, category, group, volume, packaging, scent, purpose }) =>
    ({ id, name, brand, category, group, volume, packaging, scent, purpose })),
  shelf
};
writeFile(path.join(DIST, "assets/js/catalog.js"),
  "// Generated by scripts/build.js from src/data. Do not edit.\n" +
  "(window.HC = window.HC || {}).catalog = " + JSON.stringify(catalog) + ";\n");

// "/assets/css/main.css?v=<content hash>": cached for a year, new URL whenever the file changes
const versions = new Map();
function asset(file) {
  if (!versions.has(file)) versions.set(file, md5(fs.readFileSync(path.join(DIST, "assets", file))).slice(0, 8));
  return `/assets/${file}?v=${versions.get(file)}`;
}

/* Templates */
const site = {
  ...data, hc, asset,
  year: now.getFullYear(),
  hasThumb: p => fs.existsSync(path.join(IMAGES, "products", "thumbs", p.image))
};
const ui = components(site);
const { document, redirectPage } = layout(site, ui);
const render = pages(site, ui);
const seo = seoModule(site);
const { url, escapeHtml: esc, icons } = hc;
const sitemap = createSitemap(STATE, now.toISOString().slice(0, 10));
const findCategory = id => categories.find(c => c.id === id);

const BASE_SCRIPTS = ["js/templates.js", "js/main.js"];
const CATALOG_SCRIPTS = ["js/templates.js", "js/catalog.js", "js/main.js"];
const home = { name: "Početna", path: "/" };
const crumbs = (...items) => seo.ld.breadcrumbs([home, ...items]);

// Writes a page; pages with a path are listed in the sitemap
function writePage(file, html, sitemapPath) {
  writeFile(path.join(DIST, file), html);
  if (sitemapPath) sitemap.track(sitemapPath, html);
}

/* Hand-written pages (src/pages): main content with {{placeholders}} */
const shared = {
  "company.phone": esc(company.phone),
  "company.phoneHref": ui.phoneHref,
  "company.email": esc(company.email),
  "company.address": esc(company.address),
  "company.city": esc(company.city),
  "icon.phone": icons.phone,
  "icon.mail": icons.mail,
  "icon.location": icons.location,
  "icon.check": icons.check,
  "icon.searchField": icons.search.replace("<svg", '<svg class="search-icon"')
};
function fillTemplate(file, values) {
  const template = readText(path.join(SRC, "pages", file)).trimEnd();
  return template.replace(/\{\{\s*([\w.]+)\s*\}\}/g, (match, key) => {
    const value = key in values ? values[key] : shared[key];
    if (value === undefined) throw new Error(`src/pages/${file}: unknown placeholder ${match}`);
    return value;
  });
}

let featured = data.featured.map(id => products.find(p => p.id === id)).filter(Boolean);
if (!featured.length) featured = products.slice(0, 4);

const handWritten = [
  {
    file: "home.html", out: "index.html", path: url.home, page: "home", nav: "home", scripts: CATALOG_SCRIPTS,
    seo: seo.forPage("home"), ld: [seo.ld.organization(), seo.ld.website(), seo.ld.faq(data.faq)],
    values: {
      categoryCards: ui.categoryCards(categories),
      featuredProducts: ui.productGrid(featured.slice(0, 8)),
      productCount: String(products.length),
      faq: ui.faq(data.faq),
      ctaBanner: ui.ctaBanner()
    }
  },
  {
    file: "about.html", out: "o-nama/index.html", path: url.about, page: "about", nav: "about", scripts: BASE_SCRIPTS,
    seo: seo.forPage("about"), ld: [seo.ld.organization(), crumbs({ name: "O nama", path: url.about })],
    values: { breadcrumbs: ui.breadcrumbs([{ name: "Početna", href: "/" }, { name: "O nama" }]), ctaBanner: ui.ctaBanner() }
  },
  {
    file: "contact.html", out: "kontakt/index.html", path: url.contact, page: "contact", nav: "contact", scripts: CATALOG_SCRIPTS,
    seo: seo.forPage("contact"), ld: [seo.ld.organization(), crumbs({ name: "Kontakt", path: url.contact }), seo.ld.faq(data.faq)],
    values: { breadcrumbs: ui.breadcrumbs([{ name: "Početna", href: "/" }, { name: "Kontakt" }]), faq: ui.faq(data.faq), inquiryFormRoot: ui.inquiryFormRoot() }
  },
  {
    file: "privacy.html", out: "privatnost/index.html", path: url.privacy, page: "privacy", nav: "", scripts: BASE_SCRIPTS,
    seo: seo.forPage("privacy"), ld: [crumbs({ name: "Politika privatnosti", path: url.privacy })],
    values: { breadcrumbs: ui.breadcrumbs([{ name: "Početna", href: "/" }, { name: "Politika privatnosti" }]) }
  }
];
for (const p of handWritten) {
  writePage(p.out, document({
    page: p.page, nav: p.nav, scripts: p.scripts,
    head: seo.head({ ...p.seo, path: p.path }, p.ld),
    main: fillTemplate(p.file, p.values)
  }), p.path);
}

/* Generated pages */
writePage("proizvodi/index.html", document({
  page: "catalog", nav: "products", scripts: CATALOG_SCRIPTS,
  head: seo.head({ ...seo.forPage("products"), path: url.products }, [crumbs({ name: "Svi proizvodi", path: url.products })]),
  main: render.catalog()
}), url.products);

for (const c of categories) {
  const categoryPath = url.category(c);
  writePage(categoryPath.slice(1) + "index.html", document({
    page: "category", nav: "products", scripts: BASE_SCRIPTS,
    head: seo.head({ ...seo.forCategory(c), path: categoryPath },
      [crumbs({ name: "Proizvodi", path: url.products }, { name: c.name, path: categoryPath })]),
    main: render.category(c)
  }), categoryPath);
}

for (const p of products) {
  const c = findCategory(p.category);
  const productPath = url.product(p);
  writePage(productPath.slice(1) + "index.html", document({
    page: "product", nav: "products", scripts: CATALOG_SCRIPTS,
    head: seo.head({ ...seo.forProduct(p), path: productPath, image: p.image ? url.productImage(p.image) : "", type: "product" }, [
      seo.ld.product(p, c, productPath),
      crumbs({ name: "Proizvodi", path: url.products }, { name: c.name, path: url.category(c) }, { name: p.name, path: productPath })
    ]),
    main: render.product(p)
  }), productPath);
}

writePage("404.html", document({
  page: "not-found", nav: "", scripts: BASE_SCRIPTS,
  head: seo.head({ ...seo.forPage("notFound"), noindex: true }),
  main: render.notFound()
}));

writePage("proizvod.html", redirectPage(Object.fromEntries(products.map(p => [p.id, url.product(p)])), seo.base));
writePage("kategorija.html", redirectPage(Object.fromEntries(categories.map(c => [c.id, url.category(c)])), seo.base));

writePage("sitemap.xml", sitemap.xml(seo.absolute));
const stateChanged = sitemap.save();

console.log(`Built dist/: ${products.length} products, ${categories.length} categories, ${sitemap.size()} URLs in sitemap.xml.`);
if (stateChanged) console.log("Updated scripts/build-state.json (sitemap lastmod dates).");
if (warnings.length) console.warn("Warnings:\n- " + warnings.join("\n- "));
